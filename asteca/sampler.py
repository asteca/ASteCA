import numpy as np

from .synthetic import Synthetic

# Temperature used with temperature="auto", as (max N, temperature) pairs: the first
# pair with N <= max N applies, where N is the number of stars in the observed
# cluster. Calibrated on mock clusters (coverage of the true values by the
# 16th-84th percentiles close to 68%) and checked on real clusters: T > 1 degrades
# the fit of small clusters, while for larger clusters it accounts for the mismatch
# between the model and the data (and for the random sampling of the synthetic
# clusters), which otherwise produces too narrow posteriors.
AUTO_TEMPERATURES = ((150, 1.0), (400, 2.0), (np.inf, 4.0))


class Sampler:
    """Define a :py:class:`Sampler` object.

    This object estimates the fundamental parameters of an observed cluster with
    Sequential Monte Carlo (SMC), which moves a set of particles from the prior to the
    posterior by slowly increasing the weight given to the likelihood, with persistent
    sampling (`Karamanis & Seljak 2025 <https://arxiv.org/abs/2407.20722>`__). The
    implementation is adapted from `pocoMC <https://pocomc.readthedocs.io/>`__
    (Karamanis et al. `2022a <https://ui.adsabs.harvard.edu/abs/2022MNRAS.516.1644K>`__,
    `2022b <https://arxiv.org/abs/2207.05660>`__), without its normalizing flow
    preconditioning.

    The synthetic clusters are generated by the ``synthcl`` object and compared to
    the observed cluster used to calibrate it (see
    :py:meth:`asteca.Synthetic.calibrate`) with the Poisson likelihood ratio of
    `Tremmel et al. (2013)
    <https://ui.adsabs.harvard.edu/abs/2013ApJ...766...19T/abstract>`__ (see
    :ref:`sampler_module`). The models are evaluated in batches, which is faster than
    one at a time if `numba <https://numba.pydata.org/>`__ is installed. The
    parameters that are not included in ``priors`` keep the default values of the
    ``synthcl`` object.

    The random seed is inherited from the ``synthcl`` object (its ``seed``
    attribute), which also fixes the random sampling of its synthetic clusters. The
    results are thus reproducible by setting the ``seed`` of the ``synthcl`` object.

    :param synthcl: :py:class:`asteca.Synthetic` object, calibrated with the observed
        cluster via :py:meth:`asteca.Synthetic.calibrate`
    :type synthcl: Synthetic
    :param priors: Dictionary with the ``(min, max)`` limits of the uniform priors of
        the fitted parameters, e.g.: ``{"loga": (7.0, 9.5), "dm": (8.0, 10.5)}``. The
        keys must be parameters of the ``synthcl`` object (``met, loga, alpha, beta,
        Av, DR, Rv, dm``)
    :type priors: dict[str, tuple[float, float]]
    :param temperature: Likelihood temperature, the log-likelihood is divided by
        this value. Values larger than ``1`` widen the posterior (by a factor of about
        ``sqrt(temperature)``). If ``"auto"``, it is selected from the number ``N``
        of stars in the observed cluster: ``1`` for ``N<=150``, ``2`` for
        ``N<=400``, and ``4`` above
    :type temperature: float | str
    :param n_effective: Target effective sample size used to select the next
        inverse temperature in each iteration. It is adjusted during the run based
        on the number of unique particles
    :type n_effective: int
    :param n_active: Number of particles moved with MCMC in each iteration
    :type n_active: int
    :param parallel: Evaluate the models of each batch in parallel threads (requires
        numba). Without numba it is ignored
    :type parallel: bool
    :param n_threads: Number of threads used if ``parallel=True``, for the
        duration of each batch (numba's previous setting is restored afterwards). If
        ``None``, numba's current setting is used: by default one thread per CPU
        core, which can be changed with the ``NUMBA_NUM_THREADS`` environment variable
        (before importing ``asteca``) or with ``numba.set_num_threads()``. It can not
        be larger than ``NUMBA_NUM_THREADS``
    :type n_threads: int | None
    :param verbose: Verbose level. A value of ``0`` hides all output
    :type verbose: int

    :raises ValueError: If any of the attributes is not recognized as a valid
        option, if ``synthcl`` was not calibrated, or if ``n_threads`` is used
        (``parallel=True`` with numba installed) and it is not an integer between
        ``1`` and ``NUMBA_NUM_THREADS``.
    """

    def __init__(  # noqa: DOC502, RUF100
        self,
        synthcl: Synthetic,
        priors: dict[str, tuple[float, float]],
        temperature: float | str = 1.0,
        n_effective: int = 256,
        n_active: int = 128,
        parallel: bool = False,
        n_threads: int | None = None,
        verbose: int = 1,
    ) -> None:
        self.synthcl = synthcl
        self.n_effective = int(n_effective)
        self.n_active = int(n_active)
        self.parallel = parallel
        self.n_threads = n_threads
        # The seed is inherited from the Synthetic object
        self.seed = int(synthcl.seed)
        self.verbose = verbose

        self.names = list(priors)
        self.bounds = np.array([priors[k] for k in self.names], dtype=float)
        self._check_args(temperature)

        # A legacy RandomState is used so that the results match those of pocoMC
        # (with precondition=False) for the same seed
        self.rng = np.random.RandomState(self.seed)

        # Best solution found during the run (largest log-likelihood)
        self.best_lnl = -np.inf
        self.best_params = {}

        from .modules.sampler_priv import PersistentSMC

        self._smc = PersistentSMC(
            self._log_like,
            self.bounds,
            self.n_effective,
            self.n_active,
            self.rng,
            callback=self._progress if self.verbose > 1 else None,
        )

        self._vp("\nSampler object generated")
        self._vp(f"Fitted params  : {self.names}", 1)
        self._vp(f"Temperature    : {self.temperature:g}", 1)
        self._vp(f"n_effective    : {self.n_effective}", 1)
        self._vp(f"n_active       : {self.n_active}", 1)
        if self.parallel:
            self._vp(f"Parallel       : True (n_threads={self.n_threads})", 1)
        self._vp(f"Random seed    : {self.seed}", 1)

    def _vp(self, mssg: str, level: int = 0) -> None:
        """Verbose print method"""
        if self.verbose > level:
            print(mssg)

    def _check_args(self, temperature: float | str) -> None:
        """Validate the input arguments, and set the ``temperature`` attribute"""
        self.synthcl._check_calibrated()

        if len(self.names) == 0:
            raise ValueError("At least one parameter must be included in 'priors'")
        for k, (pmin, pmax) in zip(self.names, self.bounds):
            if k not in self.synthcl.def_params:
                raise ValueError(
                    f"Parameter '{k}' not recognized. Should be one of "
                    + f"{list(self.synthcl.def_params)}"
                )
            if not (np.isfinite(pmin) and np.isfinite(pmax) and pmin < pmax):
                raise ValueError(f"Prior of '{k}' must be finite and with min < max")

        isochs = self.synthcl.isochs
        lims = {
            "met": (isochs.zmin, isochs.zmax),
            "loga": (isochs.amin, isochs.amax),
        }
        for k, (pmin, pmax) in zip(self.names, self.bounds):
            if k in lims:
                lmin, lmax = lims[k]
                if pmin < lmin or pmax > lmax:
                    raise ValueError(
                        f"Prior of '{k}' {pmin, pmax} is outside of the range of "
                        + f"the loaded isochrones [{lmin}, {lmax}]"
                    )
            elif k == "Rv" and pmin <= 0.0:
                raise ValueError("Prior of 'Rv' must be larger than 0")
            elif k != "Rv" and pmin < 0.0:
                raise ValueError(f"Prior of '{k}' must not be negative")

        if isinstance(temperature, str):
            if temperature != "auto":
                raise ValueError(
                    "'temperature' must be a positive number or 'auto', got "
                    + f"'{temperature}'"
                )
            # Number of observed stars, as in the calibration of AUTO_TEMPERATURES
            N = len(self.synthcl.cluster_mag)
            temperature = next(t for n, t in AUTO_TEMPERATURES if N <= n)
        self.temperature = float(temperature)
        if not self.temperature > 0.0:
            raise ValueError("'temperature' must be larger than 0")
        if self.n_active < 2 or self.n_effective < self.n_active:
            raise ValueError("Must have 'n_effective' >= 'n_active' >= 2")

        # Same check done by synth_batch.log_lkl_batch(), done here so that an invalid
        # value is reported before the run starts. As there, 'n_threads' is only used
        # (and checked) with parallel=True and numba installed
        from .modules import synth_batch as sb

        if (
            self.parallel
            and self.n_threads is not None
            and sb.available(self.synthcl.ext_law)
        ):
            sb.check_n_threads(self.n_threads)

    def _log_like(self, params_arr: np.ndarray) -> np.ndarray:
        """Vectorized log-likelihood, ``params_arr`` has shape
        ``(n_particles, n_dim)``"""
        from .modules import synth_batch as sb

        lnl = sb.log_lkl_batch(
            self.synthcl,
            dict(zip(self.names, params_arr.T)),
            self.temperature,
            self.parallel,
            self.n_threads,
        )
        lnl = np.asarray(lnl, dtype=float)
        lnl[~np.isfinite(lnl)] = -np.inf

        i = int(np.argmax(lnl))
        if lnl[i] > self.best_lnl:
            self.best_lnl = float(lnl[i])
            self.best_params = dict(zip(self.names, map(float, params_arr[i])))
        return lnl

    def _progress(self, particles: dict) -> None:
        """Print the progress of the run"""
        print(
            f"iter {particles['iter']:>3d} | beta {particles['beta']:.4f} | "
            + f"ESS {particles['ess']:>6.0f} | calls {particles['calls']:>7d} | "
            + f"accept {particles['accept']:.3f} | steps {particles['steps']:>3d}"
        )

    def run(self, n_total: int = 512) -> None:
        """Run the sampler.

        The run ends when the inverse temperature of the likelihood reaches ``1``
        (i.e.: the particles sample the posterior) and the effective sample size of
        the importance weighted samples of all the iterations is at least
        ``n_total``. Calling this method again with a larger ``n_total`` continues the
        run.

        :param n_total: Effective sample size of the posterior samples required to
            stop the run
        :type n_total: int
        """
        self._vp("\nRunning sampler...", 1)
        self._smc.run(n_total)

        self.n_calls = int(self._smc.calls)
        self.n_iter = int(self._smc.t)
        self.logz = float(self._smc.logz)
        _, weights, _ = self._smc.posterior()
        self.ess = float(weights.sum() ** 2 / (weights**2).sum())
        # Normalized distance of the best solution, from 0 (exact match) to 1 (no
        # overlap), see likelihood_priv.Tremmel.log_lkl()
        self.best_dist = float(
            -self.best_lnl * self.temperature / self.synthcl._lkl.lkl_range
        )

        self._vp(f"Iterations     : {self.n_iter}", 1)
        self._vp(f"Likelihood calls: {self.n_calls}", 1)
        self._vp(f"ESS            : {self.ess:.0f}", 1)
        self._vp(f"Best distance  : {self.best_dist:.3f}", 1)
        self._vp("Sampler run completed")

    def posterior(self, resample: bool = False) -> tuple[np.ndarray, np.ndarray]:
        """Posterior samples, after :py:meth:`run`.

        The samples of all the iterations are combined with importance weights
        (persistent sampling), and those with negligible weights are discarded.

        :param resample: If ``True``, return equally weighted samples (resampled
            with replacement according to their importance weights)
        :type resample: bool

        :return: ``(samples, weights)``, where ``samples`` has shape
            ``(N, n_params)`` with the columns in the order of the ``priors``
            dictionary (stored in the ``names`` attribute), and ``weights`` are the
            normalized importance weights (all equal to ``1/N`` if ``resample=True``)
        :rtype: tuple[np.ndarray, np.ndarray]

        :raises ValueError: If the sampler has not been run
        """
        if self._smc.warmup:
            raise ValueError("The sampler must be run first, see the 'run()' method")
        samples, weights, _ = self._smc.posterior(resample)
        return samples, weights

    def summary(self) -> dict[str, dict[str, float] | float]:
        """Summary statistics of the posterior of each fitted parameter, after
        :py:meth:`run`.

        The statistics are computed from the importance weighted samples returned by
        :py:meth:`posterior` (no resampling, so the result does not depend on the
        random state). The percentiles use the inverse of the weighted empirical
        CDF. The effective sample size (ESS) of these samples, ``sum(w)**2 /
        sum(w**2)`` for the weights ``w``, is the number of independent samples
        they are equivalent to: it indicates how precise the statistics are, and it
        should not be much smaller than the ``n_total`` value passed to
        :py:meth:`run`.

        The dictionaries can be passed directly to other methods, e.g.:
        ``synthcl.cluster_properties(summ["median"], summ["std"])``

        Raises a ``ValueError`` if the sampler has not been run.

        :return: Dictionary with the keys ``median, mean, std, p16, p84``, each one
            a dictionary with the value of that statistic for each fitted parameter,
            and the key ``ess`` with the effective sample size (a single value for
            all the parameters)
        :rtype: dict[str, dict[str, float] | float]
        """
        samples, weights = self.posterior()

        mean = np.sum(weights[:, None] * samples, axis=0) / np.sum(weights)
        var = np.sum(weights[:, None] * (samples - mean) ** 2, axis=0) / np.sum(weights)
        p16, p50, p84 = np.percentile(
            samples, (16, 50, 84), axis=0, weights=weights, method="inverted_cdf"
        )

        stats = {
            "median": p50,
            "mean": mean,
            "std": np.sqrt(var),
            "p16": p16,
            "p84": p84,
        }
        summ: dict[str, dict[str, float] | float] = {
            stat: dict(zip(self.names, map(float, vals)))
            for stat, vals in stats.items()
        }
        summ["ess"] = float(weights.sum() ** 2 / (weights**2).sum())
        return summ
