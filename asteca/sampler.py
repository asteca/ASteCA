import numpy as np

from .modules import HAS_NUMBA
from .modules.synthetic.engine import FULL_PARAMS
from .synthetic import Synthetic

# Temperature used with temperature="auto", as (max N, temperature) pairs: the first
# pair with N <= max N applies, where N is the number of stars in the observed
# cluster. Calibrated on mock clusters (coverage of the true values by the
# 16th-84th percentiles close to 68%) and checked on real clusters: T > 1 degrades
# the fit of small clusters, while for larger clusters it accounts for the mismatch
# between the model and the data (and for the random sampling of the synthetic
# clusters), which otherwise produces too narrow posteriors.
# With two colors these values are multiplied by 2 (the number of colors): the
# likelihood adds one Hess diagram per color, all of them sharing the magnitude, so its
# range doubles. Tested on mocks with a redundant (G-RP added to BP-RP) and an
# independent (U-B added to B-V) second color: the factor 2 restores the coverage of the
# fits with one color (and gives the same results for the redundant color), while
# keeping the gain in accuracy of the independent color. Without it the posteriors are
# too narrow (coverage ~0.5 for N<=400)
AUTO_TEMPERATURES = ((150, 1.0), (400, 2.0), (np.inf, 4.0))

# summary() warns about the parameters whose 1D posterior density at the median is
# below this fraction of the density at the main mode: the median falls between modes
# (or on a flat tail far from a peak at a prior limit). Unimodal shapes (normal,
# half-normal, exponential, lognormal) sampled with 300-800 weighted samples gave
# ratios >= 0.5 in tests; the 500-cluster UCC batch flagged 44 of 2280 marginals,
# mostly bimodal posteriors
MODE_GAP = 0.4


class Sampler:
    """Define a :py:class:`Sampler` object.

    This object estimates the fundamental parameters of an observed cluster with
    Sequential Monte Carlo (SMC), which moves a set of particles from the prior to the
    posterior by slowly increasing the weight given to the likelihood, with persistent
    sampling (`Karamanis & Seljak 2025 <https://arxiv.org/abs/2407.20722>`__). The
    implementation is adapted from `pocoMC <https://pocomc.readthedocs.io/>`__
    (Karamanis et al. `2022a <https://ui.adsabs.harvard.edu/abs/2022MNRAS.516.1644K>`__,
    `2022b <https://arxiv.org/abs/2207.05660>`__; developed by
    `Minas Karamanis <https://github.com/minaskar>`__), without its normalizing flow
    preconditioning.

    The synthetic clusters are generated by the ``synthcl`` object and compared to
    the observed cluster used to calibrate it (see
    :py:meth:`asteca.Synthetic.calibrate`) with the Poisson likelihood ratio of
    `Tremmel et al. (2013)
    <https://ui.adsabs.harvard.edu/abs/2013ApJ...766...19T/abstract>`__ (see
    :ref:`sampler_module`). The models are evaluated in batches, which is faster than
    one at a time if `numba <https://numba.pydata.org/>`__ is installed. The
    parameters that are not included in ``priors`` keep the default values of the
    ``synthcl`` object, and the differential reddening model is that of the
    ``synthcl`` object when :py:meth:`run` is called (see
    :py:attr:`asteca.Synthetic.DR_distribution`). It is stored in the
    ``DR_distribution`` attribute of the sampler.

    The random seed is inherited from the ``synthcl`` object (its ``seed``
    attribute), which also fixes the random sampling of its synthetic clusters. The
    results are thus reproducible by setting the ``seed`` of the ``synthcl`` object.

    :param synthcl: :py:class:`asteca.Synthetic` object, calibrated with the observed
        cluster via :py:meth:`asteca.Synthetic.calibrate`
    :type synthcl: Synthetic
    :param priors: Dictionary with the priors of the fitted parameters. The keys must
        be parameters of the ``synthcl`` object (``met, loga, alpha, beta, Av, DR, Rv,
        dm``), and each value is either the ``(min, max)`` limits of a uniform prior,
        or ``(dist, min, max)``: a frozen ``scipy.stats`` continuous distribution
        truncated to ``[min, max]`` (and renormalized), e.g.:
        ``{"loga": (7.0, 9.5), "met": (stats.norm(0.0, 0.15), -1.0, 0.5)}``. The
        limits must be finite and valid values of the parameters (see
        :ref:`sampler_priors`)
    :type priors: dict[str, tuple]
    :param temperature: Likelihood temperature, the log-likelihood is divided by
        this value. Values larger than ``1`` widen the posterior (by a factor of about
        ``sqrt(temperature)``). If ``"auto"``, it is selected from the number ``N``
        of stars in the observed cluster: ``1`` for ``N<=150``, ``2`` for
        ``N<=400``, and ``4`` above. These values are multiplied by the number of
        colors (i.e.: doubled if a second color is defined)
    :type temperature: float | str
    :param n_effective: Target effective sample size used to select the next
        inverse temperature in each iteration. It is adjusted during the run based
        on the number of unique particles
    :type n_effective: int
    :param n_active: Number of particles moved with MCMC in each iteration
    :type n_active: int
    :param n_threads: Number of threads used to evaluate the models of each batch
        (requires numba, without numba it is ignored). If ``1``, the models are
        evaluated serially. If larger than ``1``, they are distributed among that
        number of threads for the duration of each batch (numba's previous setting is
        restored afterwards). If ``None``, numba's current setting is used: by default
        one thread per CPU core, which can be changed with the ``NUMBA_NUM_THREADS``
        environment variable (before importing ``asteca``) or with
        ``numba.set_num_threads()``. It can not be larger than ``NUMBA_NUM_THREADS``
    :type n_threads: int | None
    :param verbose: Verbose level. A value of ``0`` hides all output
    :type verbose: int

    :raises ValueError: If any of the attributes is not recognized as a valid
        option (including a prior that is not one of the two forms above, or a
        distribution with no probability mass within its limits), if ``synthcl`` was
        not calibrated, or if ``n_threads`` is not
        ``None`` or an integer between ``1`` and ``NUMBA_NUM_THREADS`` (only checked
        with numba installed).
    """

    def __init__(  # noqa: DOC502, RUF100
        self,
        synthcl: Synthetic,
        priors: dict[str, tuple],
        temperature: float | str = 1.0,
        n_effective: int = 256,
        n_active: int = 128,
        n_threads: int | None = None,
        verbose: int = 1,
    ) -> None:
        self.synthcl = synthcl
        # Differential reddening model of the synthetic clusters, set by the first
        # call to run()
        self.DR_distribution: str | None = None
        self.n_effective = int(n_effective)
        self.n_active = int(n_active)
        self.n_threads = n_threads
        # The seed is inherited from the Synthetic object
        self.seed = int(synthcl.seed)
        self.verbose = verbose

        from .modules.prior import Prior
        from .modules.smc import PersistentSMC

        self.names = list(priors)
        # Priors, and their (min, max) limits (for the truncated distributions,
        # intersected with their support)
        self._prior = Prior(self.names, [priors[k] for k in self.names])
        self.bounds = self._prior.bounds
        # Generates the synthetic clusters and evaluates their log-likelihoods
        self._engine = synthcl._engine
        self._check_args(temperature)

        # A legacy RandomState is used so that the results match those of pocoMC
        # (with precondition=False) for the same seed
        self.rng = np.random.RandomState(self.seed)

        # Best solution found during the run (largest log-likelihood)
        self.best_lnl = -np.inf
        self.best_params = {}
        # Number of log-likelihood evaluations, and of those whose synthetic cluster
        # does not overlap the observed one, used by summary()
        self._n_lnl = 0
        self._n_lnl_no_overlap = 0

        self._smc = PersistentSMC(
            self._log_lkl_batch,
            self._prior,
            self.n_effective,
            self.n_active,
            self.rng,
            callback=self._progress if self.verbose > 1 else None,
        )

        self._print("\nSampler object generated")
        self._print(f"Fitted params  : {self.names}", 1)
        self._print(f"Temperature    : {self.temperature:g}", 1)
        self._print(f"n_effective    : {self.n_effective}", 1)
        self._print(f"n_active       : {self.n_active}", 1)
        self._print(f"Threads        : {self._n_threads_str()}", 1)
        self._print(f"Random seed    : {self.seed}", 1)

    def _n_threads_str(self) -> str:
        """Number of threads used to evaluate each batch, for the verbose output"""
        if not HAS_NUMBA:
            return "1 (numba not installed)"
        if self.n_threads is not None:
            return str(self.n_threads)
        import numba

        return f"{numba.get_num_threads()} (numba's setting)"

    def _print(self, mssg: str, level: int = 0) -> None:
        """Verbose print method"""
        if self.verbose > level:
            print(mssg)

    def _check_args(self, temperature: float | str) -> None:
        """Validate the input arguments, and set the ``temperature``, ``_obs``,
        ``_P_default`` and ``_P_cols`` attributes"""
        obs = self.synthcl._require_calibrated()
        # Observed cluster used by the likelihood. A later call to
        # 'synthcl.calibrate()' does not affect this object
        self._obs = obs

        if len(self.names) == 0:
            raise ValueError("At least one parameter must be included in 'priors'")
        for k, (pmin, pmax) in zip(self.names, self.bounds):
            if not (np.isfinite(pmin) and np.isfinite(pmax) and pmin < pmax):
                raise ValueError(f"Prior of '{k}' must be finite and with min < max")
        # The limits of the priors must be valid values of the parameters: they are
        # checked as those of the synthetic clusters (unknown names, isochrones'
        # ranges, negative values, Rv > 0). As all the priors are bounded by these
        # limits, this makes all the values that the sampler can propose valid
        try:
            corners = self._engine.validate_params(dict(zip(self.names, self.bounds)))
        except ValueError as err:
            raise ValueError(f"Invalid 'priors': {err}") from None
        # Parameters of the models evaluated by _log_lkl_batch(): the default values, with
        # the sampled ones in the columns of the fitted parameters
        self._P_default = corners[0]
        self._P_cols = [FULL_PARAMS.index(k) for k in self.names]

        if isinstance(temperature, str):
            if temperature != "auto":
                raise ValueError(
                    "'temperature' must be a positive number or 'auto', got "
                    + f"'{temperature}'"
                )
            # Number of observed stars, as in the calibration of AUTO_TEMPERATURES
            N = len(obs.mag)
            # One Hess diagram per color in the likelihood, see AUTO_TEMPERATURES
            N_colors = sum(c is not None for c in obs.colors)
            temperature = N_colors * next(t for n, t in AUTO_TEMPERATURES if N <= n)
        self.temperature = float(temperature)
        if not self.temperature > 0.0:
            raise ValueError("'temperature' must be larger than 0")
        if self.n_active < 2 or self.n_effective < self.n_active:
            raise ValueError("Must have 'n_effective' >= 'n_active' >= 2")

        # 'n_threads' is only used with numba installed. It is validated here, so
        # that an invalid value is reported before the run starts
        n_threads = self.n_threads
        if HAS_NUMBA and n_threads is not None:
            import numba

            if (
                isinstance(n_threads, bool)
                or not isinstance(n_threads, (int, np.integer))
                or n_threads < 1
            ):
                raise ValueError(
                    f"'n_threads' must be a positive integer, got {n_threads!r}"
                )
            # NUMBA_NUM_THREADS is set dynamically in numba.config (unknown to type
            # checkers)
            max_threads = numba.config.NUMBA_NUM_THREADS  # pyright: ignore[reportPrivateImportUsage, reportAttributeAccessIssue]
            if n_threads > max_threads:
                raise ValueError(
                    f"'n_threads={n_threads}' can not be larger than "
                    + f"NUMBA_NUM_THREADS={max_threads}"
                )

    def _log_lkl_batch(self, params_arr: np.ndarray) -> np.ndarray:
        """Vectorized log-likelihood, ``params_arr`` has shape
        ``(n_particles, n_dim)``"""
        # The sampler only proposes values inside the priors, which are all valid
        # (see _check_args()), so they are not validated again
        P = np.tile(self._P_default, (len(params_arr), 1))
        P[:, self._P_cols] = params_arr
        # Differential reddening model of this run, set by run()
        assert self.DR_distribution is not None
        lnl = self._engine.log_lkl_batch(
            P,
            self.DR_distribution,
            self._obs.lkl,
            self.temperature,
            self.n_threads,
        )
        lnl = np.asarray(lnl, dtype=float)
        lnl[~np.isfinite(lnl)] = -np.inf
        # Normalized distances 'd' (see likelihood.Tremmel.log_lkl()): 'd >= 1'
        # if no synthetic star falls in any bin of the observed Hess diagram, or
        # if the synthetic cluster is empty ('d = 10'). The small tolerance absorbs
        # the rounding of the conversion
        dist = self._obs.lkl.distance(lnl, self.temperature)
        self._n_lnl += lnl.size
        self._n_lnl_no_overlap += int(np.sum(dist >= 1.0 - 1e-9))

        i = int(np.argmax(lnl))
        if lnl[i] > self.best_lnl:
            self.best_lnl = float(lnl[i])
            self.best_params = dict(zip(self.names, map(float, params_arr[i])))
        return lnl

    def _progress(self, particles: dict) -> None:
        """Print the progress of the run"""
        print(
            f"iter {particles['iter']:>3d} | beta {particles['beta']:.4f} | "
            + f"ESS {particles['ess']:>6.0f} | calls {particles['calls']:>7d} | "
            + f"accept {particles['accept']:.3f} | steps {particles['steps']:>3d}"
        )

    def run(self, n_total: int = 512) -> None:
        """Run the sampler.

        The run ends when the inverse temperature of the likelihood reaches ``1``
        (i.e.: the particles sample the posterior) and the effective sample size of
        the importance weighted samples of all the iterations is at least
        ``n_total``. Calling this method again with a larger ``n_total`` continues the
        run.

        The synthetic clusters are generated with the differential reddening model of
        the ``synthcl`` object (see :py:attr:`asteca.Synthetic.DR_distribution`) at
        the time of the first call, stored in the ``DR_distribution`` attribute.

        :param n_total: Effective sample size of the posterior samples required to
            stop the run
        :type n_total: int

        :raises ValueError: If the run is continued after changing the differential
            reddening model of the ``synthcl`` object
        """
        # The model can not change within a run (the samples of all the iterations
        # are combined)
        if self.DR_distribution is None:
            self.DR_distribution = self.synthcl.DR_distribution
        elif self.synthcl.DR_distribution != self.DR_distribution:
            raise ValueError(
                "The differential reddening model of the 'synthcl' object changed "
                + f"from '{self.DR_distribution}' to "
                + f"'{self.synthcl.DR_distribution}' since this run started. Restore "
                + "it to continue the run, or create a new Sampler object"
            )

        self._print("\nRunning sampler...", 1)
        self._print(f"Diff reddening : {self.DR_distribution}", 1)
        self._smc.run(n_total)

        self.n_calls = int(self._smc.calls)
        self.n_iter = int(self._smc.t)
        self.logz = float(self._smc.logz)
        # Normalized distance of the best solution, from 0 (exact match) to 1 (no
        # overlap), see likelihood.Tremmel.log_lkl()
        self.best_dist = float(self._obs.lkl.distance(self.best_lnl, self.temperature))

        self._print(f"Iterations     : {self.n_iter}", 1)
        self._print(f"Likelihood calls: {self.n_calls}", 1)
        if self.verbose > 1:
            from .modules.smc import effective_sample_size

            # Effective sample size of the posterior samples, see summary()
            _, weights = self.posterior()
            self._print(f"ESS            : {effective_sample_size(weights):.0f}", 1)
        self._print(f"Best distance  : {self.best_dist:.3f}", 1)
        self._print("Sampler run completed")

    def posterior(self, resample: bool = False) -> tuple[np.ndarray, np.ndarray]:
        """Posterior samples, after :py:meth:`run`.

        The samples of all the iterations are combined with importance weights
        (persistent sampling), and those with negligible weights are discarded.

        :param resample: If ``True``, return equally weighted samples (resampled
            with replacement according to their importance weights)
        :type resample: bool

        :return: ``(samples, weights)``, where ``samples`` has shape
            ``(N, n_params)`` with the columns in the order of the ``priors``
            dictionary (stored in the ``names`` attribute), and ``weights`` are the
            normalized importance weights (all equal to ``1/N`` if ``resample=True``)
        :rtype: tuple[np.ndarray, np.ndarray]

        :raises ValueError: If the sampler has not been run
        """
        if self._smc.warmup:
            raise ValueError("The sampler must be run first, see the 'run()' method")
        samples, weights, _ = self._smc.posterior(resample)
        return samples, weights

    def summary(self) -> dict[str, dict[str, float]]:  # noqa: DOC502, RUF100
        """Summary statistics of the posterior of each fitted parameter, and
        diagnostics of the run, after :py:meth:`run`.

        The statistics are computed from the importance weighted samples returned by
        :py:meth:`posterior` (no resampling, so the result does not depend on the
        random state). The percentiles use the inverse of the weighted empirical
        CDF. The dictionaries of statistics can be passed directly to other methods,
        e.g.: ``synthcl.cluster_properties(summ["median"], summ["std"])``

        Statistics (one value per fitted parameter):

        - ``median, mean, std, p16, p84``: median, mean, standard deviation, and
          16th and 84th percentiles.
        - ``mode``: main mode of the 1D posterior, the maximum of its weighted
          kernel density estimate (with the density reflected at the limits of the
          prior, so a posterior that piles up against a limit has its mode there).
          A warning is issued for each parameter whose posterior density at the
          median is less than ``40%`` of that at the mode: the median falls between
          separate modes, or on a flat tail far from the peak, and the median, mean
          and percentiles do not describe a single solution (inspect the posterior,
          e.g. with a corner plot). For skewed posteriors the mode, median and mean
          differ without that being a problem.
        - ``edge_low, edge_high``: fraction of the posterior (sum of the weights)
          within ``1%`` of the width of the prior from its lower and upper limits.
          A flat posterior gives ``~0.01``. Much larger values mean that the
          posterior piles up against that limit: the prior is too narrow (or the
          fit is stuck at its limit), and the statistics of that parameter are
          truncated. This is expected for limits that are physical (e.g.: ``Av=0``
          or ``DR=0``) or that are those of the isochrones (``met, loga``), and for
          the limit of a prior distribution that peaks at it (e.g.: a half-normal
          ``DR`` prior, ``(stats.norm(0, 1), 0, 5)``).

        Mean extinction (``A_mean`` key): ``median, mean, mode, std, p16, p84`` of the
        mean extinction of the cluster stars, ``Av + f_mean * DR``, where ``f_mean``
        is the mean fraction of ``DR`` received by the stars (``0.5`` for the
        ``foreground`` differential reddening model, ``0.375`` for ``internal``; the
        model used in the run). ``Av`` or ``DR`` take their default values if they
        were not fitted, so it is equal to ``Av`` if ``DR`` was fixed to ``0``. When
        ``DR`` is fitted it is better constrained than ``Av`` and ``DR``, which are
        anti-correlated (see :ref:`mean_extinction`). It is obtained for each
        posterior sample, so its interval is not the combination of those of ``Av``
        and ``DR``.

        Diagnostics of the run (``diagnostics`` key, single values):

        - ``ess``: effective sample size of the posterior samples, ``sum(w)**2 /
          sum(w**2)`` for the weights ``w``, i.e.: the number of independent
          samples they are equivalent to. It indicates how precise the statistics
          are, and it should not be much smaller than the ``n_total`` value passed
          to :py:meth:`run`.
        - ``ess_unique``: the ESS after merging the samples with identical values
          (summing their weights). The samples of all the iterations are kept, and
          resampling and rejected MCMC moves produce copies of the same point,
          which ``ess`` counts as independent. If ``ess_unique`` is much smaller
          than ``ess``, the posterior rests on few distinct points and the
          statistics are noisier than ``ess`` suggests: run longer (larger
          ``n_total``) or with more particles (``n_effective, n_active``).
        - ``accept``: mean acceptance rate of the MCMC moves of the last iteration
          (the sampler adapts the moves towards ``~0.23``). Values close to ``0``
          mean that the particles barely moved in the posterior.
        - ``steps``: number of MCMC steps of the last iteration. The MCMC stops
          when the mean log-posterior of the particles no longer increases, or
          after ``10 * (N // 2)`` steps for ``N`` fitted parameters. Reaching this
          limit means that the particles had not settled.
        - ``no_overlap_frac``: fraction of the log-likelihood evaluations of the run
          whose synthetic cluster does not overlap the observed one: no synthetic
          star falls in any bin of the observed Hess diagram, or the synthetic
          cluster is empty (e.g.: all its stars are fainter than the maximum
          magnitude). These models get a 'no match' distance ``>= 1`` (see
          :ref:`plr`) instead of a likelihood. A large fraction means that much of
          the prior volume can not reproduce the observed cluster: the run spends
          evaluations there, and narrower priors make it faster.

        :raises ValueError: If the sampler has not been run

        :return: Dictionary with the keys ``median, mean, mode, std, p16, p84,
            edge_low, edge_high``, each one a dictionary with the value of that
            statistic for each fitted parameter, the key ``A_mean``, a dictionary with
            the keys ``median, mean, mode, std, p16, p84`` of the mean extinction, and
            the key
            ``diagnostics``, a dictionary with the keys ``ess, ess_unique, accept,
            steps, no_overlap_frac``
        :rtype: dict[str, dict[str, float]]
        """
        from .modules.smc import effective_sample_size
        from .modules.synthetic.precompute import DR_MEAN_FRAC
        from .modules.warn import warn

        samples, weights = self.posterior()
        w_sum = np.sum(weights)

        def weighted_stats(x: np.ndarray, bounds: np.ndarray) -> dict[str, np.ndarray]:
            """Weighted median, mean, main mode, STDDEV, and 16th and 84th percentiles
            of each column of ``x``, and the density at the median relative to that at
            the mode (``gap``). ``bounds`` are the limits of each column"""
            mean = np.sum(weights[:, None] * x, axis=0) / w_sum
            var = np.sum(weights[:, None] * (x - mean) ** 2, axis=0) / w_sum
            p16, p50, p84 = np.percentile(
                x, (16, 50, 84), axis=0, weights=weights, method="inverted_cdf"
            )
            mode, gap = np.array(p50, dtype=float), np.ones(x.shape[1])
            for j, (lo, hi) in enumerate(bounds):
                kde = _weighted_kde(x[:, j], weights, lo, hi)
                if kde is None:  # no spread: the mode is the median
                    continue
                grid, dens = kde
                mode[j] = grid[np.argmax(dens)]
                gap[j] = np.interp(p50[j], grid, dens) / dens.max()
            return {
                "median": p50,
                "mean": mean,
                "mode": mode,
                "std": np.sqrt(var),
                "p16": p16,
                "p84": p84,
                "gap": gap,
            }

        # Posterior mass close to the limits of the priors
        low, high = self.bounds.T
        edge = 0.01 * (high - low)
        edge_low = np.sum(weights[:, None] * (samples <= low + edge), axis=0) / w_sum
        edge_high = np.sum(weights[:, None] * (samples >= high - edge), axis=0) / w_sum

        stats = weighted_stats(samples, self.bounds)
        gap = stats.pop("gap")
        stats |= {"edge_low": edge_low, "edge_high": edge_high}
        summ = {
            stat: dict(zip(self.names, map(float, vals)))
            for stat, vals in stats.items()
        }

        # Median between separate modes (or far from the main one)
        for par, g in zip(self.names, gap):
            if g < MODE_GAP:
                warn(
                    f"The posterior of '{par}' is multimodal or strongly skewed: its "
                    + f"density at the median ({summ['median'][par]:.4g}) is "
                    + f"{100 * g:.0f}% of that at its main mode "
                    + f"({summ['mode'][par]:.4g}). The median, mean and percentiles "
                    + "do not describe a single solution: inspect the posterior"
                )

        def par_samples(par: str) -> np.ndarray:
            """Posterior samples of a parameter, or its fixed value if not fitted"""
            if par in self.names:
                return samples[:, self.names.index(par)]
            return np.full(len(samples), self._P_default[FULL_PARAMS.index(par)])

        # Mean extinction of the stars, obtained for each sample (Av and DR are
        # anti-correlated, so combining their statistics would give a too wide
        # interval). The model of the run is used
        assert self.DR_distribution is not None
        f_mean = DR_MEAN_FRAC[self.DR_distribution]
        A_mean = par_samples("Av") + f_mean * par_samples("DR")
        A_stats = weighted_stats(A_mean[:, None], np.array([[-np.inf, np.inf]]))
        A_stats.pop("gap")
        summ["A_mean"] = {stat: float(vals[0]) for stat, vals in A_stats.items()}

        # ESS of the distinct samples: the weights of identical samples are summed
        _, inv = np.unique(samples, axis=0, return_inverse=True)
        w_unique = np.bincount(inv.ravel(), weights=weights)

        summ["diagnostics"] = {
            "ess": effective_sample_size(weights),
            "ess_unique": effective_sample_size(w_unique),
            "accept": float(self._smc.current["accept"]),
            "steps": float(self._smc.current["steps"]),
            "no_overlap_frac": self._n_lnl_no_overlap / max(self._n_lnl, 1),
        }
        return summ


def _weighted_kde(
    x: np.ndarray, weights: np.ndarray, lo: float = -np.inf, hi: float = np.inf
) -> tuple[np.ndarray, np.ndarray] | None:
    """Gaussian kernel density estimate of the 1D samples ``x`` with (unnormalized)
    importance ``weights``, evaluated on a regular grid.

    The bandwidth follows Silverman's rule, ``0.9 * min(std, IQR / 1.349) *
    ESS**(-1/5)``, with the weighted ``std`` and interquartile range, and the
    effective sample size of the weights. The robust ``IQR`` term keeps the
    bandwidth from merging separate modes. The weighted samples are binned on a grid
    with a spacing of ``1/5`` of the bandwidth (between 64 and 4096 points) that
    spans the samples (plus 3 bandwidths, within ``[lo, hi]``), and convolved with
    the kernel. The density is reflected at the limits ``lo, hi`` reached by the
    grid (e.g. those of the prior), so that a posterior that piles up against a
    limit keeps its maximum there.

    :param x: Samples
    :type x: np.ndarray
    :param weights: Importance weights of the samples
    :type weights: np.ndarray
    :param lo: Lower limit of the samples
    :type lo: float
    :param hi: Upper limit of the samples
    :type hi: float

    :return: ``(grid, density)`` (density not normalized), or ``None`` if the
        samples have no spread
    :rtype: tuple[np.ndarray, np.ndarray] | None
    """
    from .modules.smc import effective_sample_size

    w = weights / np.sum(weights)
    mean = np.sum(w * x)
    std = float(np.sqrt(np.sum(w * (x - mean) ** 2)))
    q25, q75 = np.percentile(x, (25, 75), weights=w, method="inverted_cdf")
    iqr = float(q75 - q25) / 1.349
    spread = min(std, iqr) if iqr > 0 else std
    # No spread (up to the rounding errors of the weighted mean, e.g. all samples are
    # copies of the same point)
    if not spread > 1e-10 * max(abs(float(mean)), 1.0):
        return None
    bw = 0.9 * spread * effective_sample_size(w) ** (-0.2)

    a, b = max(lo, float(x.min()) - 3 * bw), min(hi, float(x.max()) + 3 * bw)
    n_grid = int(np.clip((b - a) / (bw / 5), 64, 4096))
    dx = (b - a) / n_grid
    hist, edges = np.histogram(x, bins=n_grid, range=(a, b), weights=w)
    n_k = int(np.ceil(4 * bw / dx))
    kernel = np.exp(-0.5 * (np.arange(-n_k, n_k + 1) * dx / bw) ** 2)

    def first_bins(h: np.ndarray) -> np.ndarray:
        """First n_k values of h, zero padded"""
        out = np.zeros(n_k)
        out[: min(n_k, len(h))] = h[:n_k]
        return out

    # Mirror the histogram at the limits reached by the grid, zeros elsewhere
    left = first_bins(hist)[::-1] if a == lo else np.zeros(n_k)
    right = first_bins(hist[::-1]) if b == hi else np.zeros(n_k)
    dens = np.convolve(np.concatenate([left, hist, right]), kernel, mode="same")
    return 0.5 * (edges[1:] + edges[:-1]), dens[n_k : n_k + n_grid]
