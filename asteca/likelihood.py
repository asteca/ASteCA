from typing import Literal

import numpy as np


class Likelihood:
    """Define a :py:class:`Likelihood` object.

    This object is used to assess how similar your observed cluster is, stored in
    a :py:class:`asteca.Cluster` object,  compared to a given
    synthetic cluster, generated by the :py:meth:`asteca.Synthetic.generate` method.

    :param my_cluster: :py:class:`asteca.Cluster` object with the
        loaded data for the observed cluster
    :type my_cluster: Cluster
    :param lkl_name: Currently only the Poisson likelihood ratio (``plr``) defined in
        `Tremmel et al. (2013)
        <https://ui.adsabs.harvard.edu/abs/2013ApJ...766...19T/abstract>`__
        is accepted
    :type lkl_name: str
    :param bin_method: Bin method used to split the color-magnitude diagram into cells
        (`Hess diagram <https://en.wikipedia.org/wiki/Hess_diagram>`__); one of:
        ``knuth, blocks, scott, freedman or fixed``. See
        `Choosing Histogram Bins <https://docs.astropy.org/en/stable/visualization/histogram.html>`__
        in `astropy <https://www.astropy.org/>`__ documentation for details on the
        ``knuth, blocks, scott, freedman`` methods.  The method ``fixed``
        uses (15, 10) bins in magnitude and color(s) respectively
    :type bin_method: Literal["blocks", "knuth", "scott", "freedman", "fixed"]
    :param verbose: Verbose level. A value of ``0`` hides all output
    :type verbose: int

    :raises ValueError: If any of the attributes is not recognized as a valid option
    """

    from .cluster import Cluster

    def __init__(
        self,
        my_cluster: Cluster,
        lkl_name: str = "plr",
        bin_method: Literal["blocks", "knuth", "scott", "freedman", "fixed"] = "knuth",
        verbose: int = 1,
    ) -> None:
        self.lkl_name = lkl_name
        self.bin_method = bin_method
        self.verbose = verbose

        likelihoods = ("plr",)
        if self.lkl_name not in likelihoods:
            raise ValueError(
                f"'{self.lkl_name}' not recognized. Should be one of {likelihoods}"
            )

        bin_methods = ("blocks", "knuth", "scott", "freedman", "fixed")
        if self.bin_method not in bin_methods:
            raise ValueError(
                f"Binning '{self.bin_method}' not recognized. "
                + f"Should be one of {bin_methods}"
            )

        if my_cluster.mag is None or my_cluster.color is None:
            raise ValueError(
                "This method requires a photometric magnitude and at least one color\n"
                + "defined in the 'Cluster' object"
            )

        # Extract photometry from 'Cluster' object
        self.mag = my_cluster.mag
        self.color = my_cluster.color
        color2 = my_cluster.color2

        from .modules import likelihood_priv as lpriv

        # Data used by the `get()` method
        self.m_ini_idx = 2  # (0->mag, 1->color, 2->mass_ini)
        if color2 is not None:
            self.m_ini_idx = 3  # (0->mag, 1->color, 2->color2, 3->mass_ini)

        colors = [self.color]
        if color2 is not None:
            colors += [color2]

        # Obtain data used by the ``dist()`` and ``log_lkl()`` methods
        self.ranges, self.Nbins = lpriv.bin_edges_f(bin_method, self.mag, colors)
        self.cl_z_idx, self.cl_histo_f_z, self.table2d = lpriv.lkl_data(
            self.mag, colors, self.ranges, self.Nbins
        )
        self.obs_mag_median = np.nanmedian(self.mag).astype(float)
        self.obs_col_median = np.nanmedian(colors[0]).astype(float)
        # Widths of the Hess diagram ranges for the magnitude and (first) color, used
        # to scale the dimensions of the no-overlap penalty
        self.cmd_widths = (
            float(self.ranges[0][1] - self.ranges[0][0]),
            float(self.ranges[1][1] - self.ranges[1][0]),
        )

        # Pre-compute 'tremmel' parameters
        # Per-color histogram2d arguments: (nx, xmin, xmax, ny, ymin, ymax)
        self.hist_args = np.array(
            [
                (
                    self.Nbins[0],
                    self.ranges[0][0],
                    self.ranges[0][1],
                    self.Nbins[i],
                    self.ranges[i][0],
                    self.ranges[i][1],
                )
                for i in range(1, len(self.Nbins))
            ],
            dtype=float,
        )
        # Positions of the non-empty observed bins in the flattened Hess diagram
        self.nz_pos = np.flatnonzero(self.cl_z_idx)
        # Flattened table and row offsets, so that table2d[n, m] becomes
        # table_flat[row_off + m]
        self.table_flat = self.table2d.ravel()
        self.row_off = self.cl_histo_f_z.astype(np.intp) * self.table2d.shape[1]
        # Largest number of synthetic stars per bin covered by the table
        self.m_max = int(self.table2d.shape[1] - 1)
        tremmel_args = (
            self.hist_args,
            self.nz_pos,
            self.row_off,
            self.table_flat,
            self.m_max,
        )
        # Minimum likelihood, obtained when no synthetic star falls in any observed
        # bin (all m_i=0). Used to normalize the distance so that 1 means no match.
        # This is equal to 'table_flat.take(row_off).sum()' but it is obtained with
        # the same core that evaluates the synthetic clusters (a single star below
        # the lower limit of every range), so that the sum is performed in the same
        # order and the 'lkl <= min_lkl' check in _eval() is not affected by rounding
        no_overlap_star = np.array(
            [[self.hist_args[0, 1] - 1.0]]
            + [[ymin - 1.0] for ymin in self.hist_args[:, 4]]
        )
        self.min_lkl = float(lpriv.tremmel(*tremmel_args, no_overlap_star))

        # Maximum likelihood, obtained evaluating the cluster against itself. This is
        # equal to: sum([gammaln(2*_ + 0.5) - gammaln(_ + 0.5) for _ in cl_histo_f_z])
        self.max_lkl = float(
            lpriv.tremmel(*tremmel_args, np.array([self.mag, *colors]))
        )
        # Range of the likelihood for synthetic clusters that overlap the observed
        # one, used to convert between log-likelihoods and distances
        self.lkl_range = self.max_lkl - self.min_lkl

        self._vp("\nLikelihood object generated")

    def _vp(self, mssg: str, level: int = 0) -> None:
        """Verbose print method"""
        if self.verbose > level:
            print(mssg)

    def dist(self, synth_clust: np.ndarray) -> float:
        """Distance between the observed cluster and a synthetic cluster, for
        distance-based samplers or optimizers (e.g.: ABC, differential evolution).

        This is the normalized and inverted likelihood:
        ``(max_lkl - lkl) / (max_lkl - min_lkl)``, which goes from ``0`` (exact match)
        to ``1`` (no synthetic star in any of the observed bins). Synthetic clusters
        with no overlap get ``1`` plus a penalty that grows with their photometric
        distance to the observed cluster, and empty synthetic clusters get ``10``.

        :param synth_clust: Array containing the synthetic cluster data. The
            shape of this array is assumed to be: ``[magnitude, color1, (color2)]``,
            where ``magnitude`` and ``color`` are arrays with the synthetic magnitude
            and color photometric data (``color2`` is the optional second color defined)
            If the array contains any extra columns beyond these they will be ignored.
        :type synth_clust: np.ndarray

        :return: Distance value, ``0`` is the best value
        :rtype: float
        """
        # lkl = self._eval(synth_clust)
        # Since table2d[n, m] grows with m for n>0, lkl >= min_lkl and thus dist <= 1
        # for synthetic clusters that overlap the observed one (see _eval() for the
        # rest).
        # This is only a rescaling of '1 - lkl / max_lkl', it does not change the
        # ordering of the distances but puts the values on the same 0–1 scale for all
        # clusters (1 = no overlap)
        return (self.max_lkl - self._eval(synth_clust)) / self.lkl_range

    def log_lkl(self, synth_clust: np.ndarray, temperature: float = 1.0) -> float:
        """Log-likelihood of a synthetic cluster, for likelihood-based samplers
        (e.g.: MCMC, sequential Monte Carlo, nested sampling).

        The value is ``(lkl - max_lkl) / temperature``, i.e.: the log-likelihood
        relative to its maximum (the observed cluster evaluated against itself), so
        that ``0`` is the best value. This equals ``-dist * (max_lkl - min_lkl) /
        temperature``, where ``dist`` is the value returned by :py:meth:`dist`, which
        is also used for synthetic clusters with no overlap with the observed one
        (and for empty ones), so that these are not all assigned the same value.

        The ``temperature`` flattens the likelihood (tempered or "power" likelihood),
        which widens the posterior by a factor of about ``sqrt(temperature)``. Values
        larger than ``1`` can be used to account for sources of uncertainty not
        included in the likelihood, e.g.: the random sampling of the synthetic
        clusters or the mismatch between the model and the observed data, which
        dominate for clusters with many members.

        :param synth_clust: Array containing the synthetic cluster data, same as in
            :py:meth:`dist`
        :type synth_clust: np.ndarray
        :param temperature: Likelihood temperature, must be positive. Defaults to
            ``1`` (no tempering)
        :type temperature: float

        :return: Log-likelihood value, ``0`` is the best value
        :rtype: float
        """
        return (self._eval(synth_clust) - self.max_lkl) / temperature

    def _eval(self, synth_clust: np.ndarray) -> float:
        """Core shared by :py:meth:`dist` and :py:meth:`log_lkl`.

        Returns the log-likelihood of the synthetic cluster if it overlaps the
        observed bins. Otherwise the raw value would be ``min_lkl`` for every such
        model, so a 'no match' distance ``d >= 1`` is assigned instead (``10`` for an
        empty synthetic cluster, or a penalty that grows with its photometric
        distance to the observed cluster) and converted to log-likelihood units as
        ``max_lkl - d * (max_lkl - min_lkl)``, so that :py:meth:`dist` returns ``d``.

        :param synth_clust: Array containing the synthetic cluster data
        :type synth_clust: np.ndarray

        :return: Log-likelihood value
        :rtype: float
        """
        from .modules import likelihood_priv as lpriv

        # Ignore any extra columns beyond the main photometry
        synth_clust = synth_clust[: self.m_ini_idx]

        # Empty synthetic cluster, assign '10' indicating a large distance
        if synth_clust.size == 0:
            # no_match_dist = 10.0
            # Convert penalty from distance scale to log-likelihood scale
            return self.max_lkl - 10.0 * self.lkl_range

        # Compute the Tremmel log-likelihood of the synthetic cluster
        lkl = lpriv.tremmel(
            self.hist_args,
            self.nz_pos,
            self.row_off,
            self.table_flat,
            self.m_max,
            synth_clust,
        )

        # No synthetic star falls in any observed bin
        if lkl <= self.min_lkl:
            no_match_dist = lpriv.no_overlap_dist(
                self.obs_mag_median, self.obs_col_median, self.cmd_widths, synth_clust
            )
            # Convert penalty from distance scale to log-likelihood scale
            return self.max_lkl - no_match_dist * self.lkl_range

        return lkl

    def cmd_overlap(
        self, synth_clust: np.ndarray, h_mag: float = 0.3, h_col: float = 0.075
    ) -> tuple[float, float]:
        """Goodness of fit of a synthetic cluster, that can be compared across
        observed clusters with any number of stars.

        The value is ``D = 1 - 2 * K_os / (K_oo + K_ss)``, where ``K_os`` is the mean
        value of a Gaussian kernel (with widths ``h_mag`` and ``h_col``) over all the
        pairs of observed and synthetic stars, and ``K_oo`` and ``K_ss`` are the mean
        values over the pairs of distinct observed stars and of distinct synthetic
        stars. ``D`` is the normalized squared difference between the observed and
        synthetic densities in the CMD (magnitude and first color), both smoothed
        with the kernel: ``0`` means the same distribution and ``1`` means no overlap.

        Since stars are never compared with themselves, a synthetic cluster drawn
        from the same distribution as the observed one gives ``D=0`` on average for
        any number of stars, and a given mismatch gives on average the same ``D`` for
        any number of stars. Individual values fluctuate around ``0`` and can be
        negative: ``D<0`` is a match within the noise (compare it with ``D_std``),
        not an error. Values are not clipped to ``0``, as this would bias their
        average upwards. ``D<=0.25`` is a reasonable general threshold for a good
        fit (see the documentation). The kernel widths set the scale at which the
        CMDs are compared, so the same values must be used for all the clusters
        whose ``D`` values are compared.

        A ``ValueError`` is raised if the observed cluster has fewer than two stars
        with valid photometry.

        :param synth_clust: Array containing the synthetic cluster data. The
            shape of this array is assumed to be: ``[magnitude, color1, ...]``. Only
            the magnitude and the first color are used.
        :type synth_clust: np.ndarray
        :param h_mag: Width of the Gaussian kernel in magnitude, defaults to ``0.3``
        :type h_mag: float
        :param h_col: Width of the Gaussian kernel in color, defaults to ``0.075``
        :type h_col: float

        :return: ``(D, D_std)``, where ``D_std`` is the approximate standard
            deviation of ``D`` for a synthetic cluster drawn from the same
            distribution as the observed one (it decreases with the number of stars).
            If the synthetic cluster has fewer than two stars, ``D=1`` and ``D_std=0``
        :rtype: tuple[float, float]
        """
        from .modules import likelihood_priv as lpriv

        D, D_std = lpriv.cmd_overlap(self.mag, self.color, synth_clust, h_mag, h_col)

        return D, D_std
